import type { NextConfig } from "next";

const isProd = process.env.NODE_ENV === "production";

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isProd ? "" : " 'unsafe-eval'"}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  ...(isProd
    ? [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" }]
    : []),
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  async redirects() {
    return [
      { source: "/grid", destination: "/demo/timetable", permanent: false },
      { source: "/timetable", destination: "/demo/timetable", permanent: false },
      { source: "/vacancy", destination: "/demo/find", permanent: false },
      { source: "/dashboard", destination: "/demo", permanent: false },
      { source: "/timetable/upload", destination: "/demo/manage/upload", permanent: false },
      { source: "/students", destination: "/demo/manage/students", permanent: false },
      { source: "/students/upload", destination: "/demo/manage/students", permanent: false },
    ];
  },
};

export default nextConfig;
